/* ---------------------------------------------------------
 * Animation API
 * --------------------------------------------------------- */

uint8_t anim_frame = 0;
static uint16_t anim_timer = 0;

void invader_anim_init(void)
{
    anim_frame = 0;
    anim_timer = 0;
}

void invader_anim_update(void)
{
    anim_timer++;

/* Animation wird pro Level schneller */
extern int level;

uint16_t speed = 120 - (level * 10);
if (speed < 40) speed = 40;   // Mindestgeschwindigkeit

if (anim_timer > speed) {
    anim_timer = 0;
    anim_frame = (anim_frame + 1) & 3;
}
}

const Sprite4 *invader_anim_get(uint8_t type, uint8_t frame)
{
    switch (type % 3) {
    case 0: return &invader_t1[frame];
    case 1: return &invader_t2[frame];
    default: return &invader_t3[frame];
    }
}
